// Generate random sparkline data
const generateSparkline = (): number[] => {
  const points = [];
  let value = 0.4 + Math.random() * 0.2;
  for (let i = 0; i < 24; i++) {
    value += (Math.random() - 0.5) * 0.08;
    value = Math.max(0.1, Math.min(0.9, value));
    points.push(value);
  }
  return points;
};

