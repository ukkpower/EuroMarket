// Helper function to convert label to id (slug format)
const labelToId = (label: string): string => {
  return label
    .toLowerCase()
    .replace(/[&]/g, 'and')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
};

